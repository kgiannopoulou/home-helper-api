<?php

namespace App\Console\Commands;

use Illuminate\Console\Command;
use Illuminate\Support\Collection;
use Illuminate\Support\Facades\DB;

/**
 * Writes docs/database.md: Mermaid ER diagrams drawn from the live schema
 * (information_schema), so the picture can't drift from the migrations.
 * One overview of every table and foreign key, then one diagram per module
 * with the columns.
 */
class SchemaDiagram extends Command
{
    protected $signature = 'docs:schema {--path=docs/database.md}';

    protected $description = 'Draw the database schema as Mermaid ER diagrams';

    /** Module => its tables, in reading order */
    private const MODULES = [
        'Households and accounts' => ['users', 'households', 'household_user', 'invites', 'devices', 'personal_access_tokens', 'job_runs'],
        'Money' => ['recurring_bills', 'expenses', 'budgets'],
        'Shopping and kitchen' => ['shopping_trips', 'shopping_items', 'item_prices', 'inventory_items', 'purchases'],
        'Chores' => ['rooms', 'chores', 'chore_completions', 'supplies'],
        'Health logs' => ['food_entries', 'water_entries', 'sleep_entries', 'workouts', 'weights', 'step_counts'],
        'Planner and life admin' => ['events', 'todos', 'admin_items'],
    ];

    /** Columns every synced table has; described once in the intro instead */
    private const BOOKKEEPING = ['created_at', 'updated_at', 'deleted_at', 'synced_at'];

    public function handle(): int
    {
        $tables = collect(self::MODULES)->flatten()->all();
        $columns = $this->columns($tables);
        $foreignKeys = $this->foreignKeys($tables);

        $missing = array_diff($tables, $columns->keys()->all());
        if ($missing) {
            $this->error('Not in the database (run the migrations first): '.implode(', ', $missing));

            return self::FAILURE;
        }

        $md = [
            '# Database',
            '',
            '<!-- Generated by `php artisan docs:schema` from the live MySQL schema. Do not edit by hand. -->',
            '',
            'Every household table has a ULID `id`, `household_id`, millisecond `created_at`/`updated_at`/`deleted_at` and a `synced_at` cursor for phone sync (left out of the module diagrams below to keep them readable). Design notes: [database-design.md](database-design.md).',
            '',
            '## Overview',
            '',
            '```mermaid',
            'erDiagram',
            // Every module table also belongs to a household; those edges are
            // drawn in the module diagrams, here they'd hide everything else
            ...$this->relationships($foreignKeys->reject(
                fn ($fk) => $fk->column === 'household_id' && ! in_array($fk->table, self::MODULES['Households and accounts']),
            ), $tables),
            '```',
        ];

        foreach (self::MODULES as $module => $moduleTables) {
            $md[] = '';
            $md[] = "## $module";
            $md[] = '';
            $md[] = '```mermaid';
            $md[] = 'erDiagram';
            foreach ($moduleTables as $table) {
                $md[] = "    $table {";
                foreach ($columns[$table]->reject(fn ($c) => in_array($c->name, self::BOOKKEEPING)) as $column) {
                    $md[] = '        '.$this->attribute($column, $foreignKeys);
                }
                $md[] = '    }';
            }
            // Relationships that touch this module; tables from other modules appear as bare boxes
            $md = [...$md, ...$this->relationships($foreignKeys->filter(fn ($fk) => in_array($fk->table, $moduleTables)), $tables)];
            $md[] = '```';
        }

        file_put_contents(base_path($this->option('path')), implode("\n", $md)."\n");
        $this->info('Wrote '.$this->option('path').' ('.count($tables).' tables, '.$foreignKeys->count().' foreign keys).');

        return self::SUCCESS;
    }

    /**
     * @return Collection<string, Collection<int, object>>
     */
    private function columns(array $tables): Collection
    {
        return collect(DB::select(
            'SELECT TABLE_NAME AS `table`, COLUMN_NAME AS name, DATA_TYPE AS type, COLUMN_KEY AS `key`,
                    IS_NULLABLE AS nullable, EXTRA AS extra
             FROM information_schema.COLUMNS
             WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME IN ('.implode(',', array_fill(0, count($tables), '?')).')
             ORDER BY TABLE_NAME, ORDINAL_POSITION',
            $tables,
        ))->groupBy('table');
    }

    /**
     * @return Collection<int, object{table: string, column: string, references: string, nullable: string}>
     */
    private function foreignKeys(array $tables): Collection
    {
        return collect(DB::select(
            'SELECT k.TABLE_NAME AS `table`, k.COLUMN_NAME AS `column`, k.REFERENCED_TABLE_NAME AS `references`,
                    c.IS_NULLABLE AS nullable
             FROM information_schema.KEY_COLUMN_USAGE k
             JOIN information_schema.COLUMNS c
               ON c.TABLE_SCHEMA = k.TABLE_SCHEMA AND c.TABLE_NAME = k.TABLE_NAME AND c.COLUMN_NAME = k.COLUMN_NAME
             WHERE k.TABLE_SCHEMA = DATABASE() AND k.REFERENCED_TABLE_NAME IS NOT NULL
               AND k.TABLE_NAME IN ('.implode(',', array_fill(0, count($tables), '?')).')
             ORDER BY k.TABLE_NAME, k.COLUMN_NAME',
            $tables,
        ));
    }

    /**
     * parent ||--o{ child : "column"  (|o when the foreign key is optional)
     *
     * @return list<string>
     */
    private function relationships(Collection $foreignKeys, array $tables): array
    {
        return $foreignKeys
            ->filter(fn ($fk) => in_array($fk->references, $tables))
            ->map(fn ($fk) => sprintf(
                '    %s %s--o{ %s : "%s"',
                $fk->references,
                $fk->nullable === 'YES' ? '|o' : '||',
                $fk->table,
                $fk->column,
            ))
            ->values()
            ->all();
    }

    private function attribute(object $column, Collection $foreignKeys): string
    {
        $keys = [];
        if ($column->key === 'PRI') {
            $keys[] = 'PK';
        }
        if ($foreignKeys->contains(fn ($fk) => $fk->table === $column->table && $fk->column === $column->name)) {
            $keys[] = 'FK';
        }
        if ($column->key === 'UNI') {
            $keys[] = 'UK';
        }

        $notes = array_filter([
            $column->nullable === 'YES' ? 'nullable' : null,
            str_contains($column->extra, 'GENERATED') ? 'generated' : null,
        ]);

        return implode(' ', array_filter([
            $column->type,
            $column->name,
            implode(', ', $keys),
            $notes ? '"'.implode(', ', $notes).'"' : '',
        ]));
    }
}
